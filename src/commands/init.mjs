// `fastpix-supabase init` — copy the package's files into the user's supabase dir, patch
// config.toml, write the .env template, and create the fastpix tables. Everything is
// copy-if-absent, so re-running is safe.
import { runMigrations } from "@fastpix/fp-sync-engine";
import {
  MIGRATIONS_DIR,
  PKG,
  FUNCTIONS,
  handlerFor,
  ok,
  skip,
  ask,
  supabaseDir,
  copyInto,
  resolveDatabaseUrl,
  applyQueueMigrations,
} from "./utils.mjs";
import { patchConfigToml } from "./toml-modifications.mjs";
import path from "node:path";
import fs from "node:fs";

const ENV_TEMPLATE = `# Used to develop Edge Functions locally.
# Configure the secrets required by the fastpix functions.
FASTPIX_WEBHOOK_SECRET=your-fastpix-webhook-secret
FASTPIX_TOKEN_ID=your-fastpix-token-id
FASTPIX_TOKEN_SECRET=your-fastpix-token-secret
`;

/**
 * Write one edge function: a three-line entry point plus its import map.
 *
 * The handler itself lives in `@fastpix/supabase/deno` (dist/deno.js) rather than being copied into
 * the user's repo, so a patched handler reaches them by bumping this package instead of re-running
 * init and diffing four files by hand. Pinned to the exact version that generated it, so a later
 * publish never silently changes a deployed function.
 *
 * Returns true when it created the function, false when one was already there.
 */
function writeFunction(dir, fn) {
  if (fs.existsSync(dir)) {
    skip(`${fn} already exists, leaving it alone`);
    return false;
  }
  fs.mkdirSync(dir, { recursive: true });

  const handler = handlerFor(fn);
  fs.writeFileSync(
    path.join(dir, "index.ts"),
    `// Generated by \`npx @fastpix/supabase init\`. The handler is versioned with the package —
// change the pin in deno.json to move it, or inline your own logic here to fork it.
import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { ${handler} } from "@fastpix/supabase/deno";

Deno.serve(${handler});
`,
  );
  fs.writeFileSync(
    path.join(dir, "deno.json"),
    `${JSON.stringify(
      {
        imports: {
          "@fastpix/supabase/deno": `npm:@fastpix/supabase@${PKG.version}/deno`,
        },
      },
      null,
      2,
    )}\n`,
  );
  return true;
}

function writeEnvFile(dir, creds) {
  const file = path.join(dir, "functions", ".env");
  if (fs.existsSync(file)) {
    skip("supabase/functions/.env already exists. Skipping creation.");
    return;
  }
  let content = ENV_TEMPLATE;
  for (const [key, value] of Object.entries(creds)) {
    if (value)
      content = content.replace(
        new RegExp(`^${key}=.*$`, "m"),
        `${key}=${value}`,
      );
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  ok("Created supabase/functions/.env");
}

export async function init() {
  const dir = supabaseDir();

  const migrations = fs
    .readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith(".sql"));
  const copiedMigrations = copyInto(
    MIGRATIONS_DIR,
    path.join(dir, "migrations"),
    migrations,
  );
  if (copiedMigrations)
    ok(`Copied ${copiedMigrations} migration(s) into supabase/migrations`);

  const createdFunctions = FUNCTIONS.filter((fn) =>
    writeFunction(path.join(dir, "functions", fn), fn),
  ).length;
  if (createdFunctions) {
    ok(
      `Created ${createdFunctions} function(s) in supabase/functions which use @fastpix/fp-sync-engine to sync your data`,
    );
  }

  patchConfigToml(dir);

  console.log(
    "\nFastPix credentials (from your FastPix dashboard). Press enter to fill these in later.",
  );
  const creds = {
    FASTPIX_TOKEN_ID: await ask("  FASTPIX_TOKEN_ID: "),
    FASTPIX_TOKEN_SECRET: await ask("  FASTPIX_TOKEN_SECRET: "),
    FASTPIX_WEBHOOK_SECRET: await ask("  FASTPIX_WEBHOOK_SECRET: "),
  };
  writeEnvFile(dir, creds);

  // The fastpix schema belongs to the engine, not to a migration in this package, so it is created
  // here rather than by `supabase db reset`.
  const databaseUrl =
    resolveDatabaseUrl() ||
    (await ask(
      "\nDatabase URL to create the fastpix tables in (enter to skip):\n(`supabase status -o env` shows it as DB_URL) ",
    ));
  if (databaseUrl) {
    await applyQueueMigrations(databaseUrl);
    await runMigrations({ databaseUrl });
    ok("Created the fastpix schema and its tables");
  } else {
    skip(
      "Skipped database setup. Set SUPABASE_DB_URL and run `npx @fastpix/supabase migrate` before your first webhook.",
    );
  }

  console.log("\nNext steps:");
  console.log(
    "  1. npx supabase stop && npx supabase start   (picks up the config.toml changes)",
  );
  console.log("  2. npx supabase functions serve");
  console.log("  3. Point a FastPix webhook at /functions/v1/fastpix-webhook");
}
